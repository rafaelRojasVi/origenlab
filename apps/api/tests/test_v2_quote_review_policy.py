def _oq(number: str, addressee: str, *, header: list[str] = ORIGEN, **kw) -> list[str]:
    """An OrigenLab quotation: the identity suite's layout under OrigenLab's own header."""
    return header + _quote(number, addressee, **kw)[len(HEADER):]


@pytest.fixture
def world(tmp_path: Path) -> World:
    return World(tmp_path)


def _direction(world: World, email_id: int, hint: str) -> None:
    rec = next(r for r in world.records if r["payload"]["source_email_id"] == email_id)
    rec["payload"]["direction_hint"] = hint


def _run(world: World, *, email_ledger: list[dict] | None = None, doc_ledger: list[dict] | None = None):
    report, _ = world.audit()
    staging = qr.load_staging(world.staging_dir)
    review = dr.build_document_review(staging, report)
    issuers = {c.sha256: qp.document_issuer(qd.extract_text(world.docs_dir / f"{c.sha256}.pdf").text)
               for c in review.candidates}
    ledger_dir = world.root / "review"
    ledger_dir.mkdir(exist_ok=True)
    email_path, doc_path = ledger_dir / "decisions.jsonl", ledger_dir / dr.DOCUMENT_LEDGER_FILE
    for path, rows in ((email_path, email_ledger or []), (doc_path, doc_ledger or [])):
        path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    email_states = qr.DecisionLedger(email_path).states()
    doc_states = effective_document_states(review, dr.DocumentDecisionLedger(doc_path), email_states)
    return review, qp.dry_run(staging, review, issuers, doc_states, email_states, own_senders=OWN_SENDERS)


def _sha_of(review: dr.DocumentReview, number: str) -> str:
    return next(c.sha256 for c in review.candidates if number in c.printed_quote_numbers)


def _email_decision(email_id: int, decision: str, number: str | None = None, mode: str | None = None) -> dict:
    return {"decision_id": f"d-{email_id}-{decision}", "recorded_at": "2026-09-24T10:00:00+00:00",
            "operator": "op@example.cl", "email_id": email_id, "decision": decision, "quote_number": number,
            "opportunity": {"mode": mode, "opportunity_id": None} if mode else None}


def _doc_decision(sha: str, email_id: int, number: str | None, mode: str = "create_new",
                  decision: str = qr.DECISION_CONFIRM, planned: str = "00000000-0000-4000-8000-000000000001") -> dict:
    return {"target": dr.TARGET_DOCUMENT, "document_sha256": sha, "decision": decision,
            "canonical_email_id": email_id, "quote_number": number,
            "opportunity": ({"mode": mode, "opportunity_id": None, "planned_opportunity_id": planned}
                            if decision == qr.DECISION_CONFIRM else None)}


def _comparison(run: qp.DryRun, key: str) -> qp.LedgerComparison:
    return next(c for c in run.comparison if c.key == key)


