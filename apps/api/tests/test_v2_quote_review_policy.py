    assert _comparison(run, adventista).outcome == qp.POLICY_STRICTER
    revision = run.documents[_sha_of(review, "01065A-26")]
    # The revision shares serial 1065 with Adventista's version and with Valparaíso's quote.
    assert {qp.R_VERSION_CHANGE, qp.R_CLIENT_CONFLICT} <= set(revision.reasons)
    assert not revision.automatable


