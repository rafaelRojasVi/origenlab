def test_module_imports_no_database_driver_and_opens_no_file() -> None:
    tree = ast.parse(_MODULE.read_text(encoding="utf-8"))
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported |= {a.name for a in node.names}
        elif isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
    forbidden = ("psycopg", "sqlite3", "sqlalchemy", "origenlab_api.v2.repository",
                 "origenlab_api.v2.command", "googleapiclient", "requests", "httpx", "urllib",
                 "subprocess", "os", "pathlib")
    assert not [m for m in imported if m.startswith(forbidden)], imported
    calls = {getattr(n.func, "attr", getattr(n.func, "id", None)) for n in ast.walk(tree) if isinstance(n, ast.Call)}
    assert not calls & {"open", "write_text", "write_bytes", "unlink", "mkdir"}
    assert not [n for n in ast.walk(tree) if isinstance(n, ast.Call)
                and isinstance(n.func, ast.Attribute) and n.func.attr == "append"
                and "ledger" in ast.unparse(n.func.value)]


def _load_script():
    spec = importlib.util.spec_from_file_location("quote_review_policy_dryrun", _SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def test_dry_run_script_writes_only_its_report_and_leaves_the_ledgers_untouched(world, tmp_path) -> None:
    quote = world.file("CN01005-Bioeq SpA.pdf", _oq("1005-26", "Bioeq SpA"))
    world.email(1, [quote])
    world.email(2, [world.file("CN1051-x.pdf", _oq("01051-26", "hola@ongo.example.cl"))])
    report, _ = world.audit()
    identity = tmp_path / "identity"
    (identity / "texts").mkdir(parents=True)
    (identity / "quote_document_identity.json").write_text(json.dumps(report), encoding="utf-8")
    for d in report["documents"]:
        text = qd.extract_text(world.docs_dir / f"{d['sha256']}.pdf").text
        (identity / "texts" / f"{d['sha256']}.txt").write_text(text, encoding="utf-8")
    ledger = tmp_path / "review" / "decisions.jsonl"
    ledger.parent.mkdir()
    ledger.write_text(json.dumps(_email_decision(2, qr.DECISION_PENDING)) + "\n", encoding="utf-8")
    doc_ledger = ledger.with_name(dr.DOCUMENT_LEDGER_FILE)
    doc_ledger.write_text(json.dumps(_doc_decision(quote[1], 1, "1005-26")) + "\n", encoding="utf-8")
    hashes = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in (ledger, doc_ledger)}

    out = tmp_path / "out"
    mod = _load_script()
    argv = ["--staging-dir", str(world.staging_dir), "--identity-dir", str(identity),
            "--ledger", str(ledger), "--out", str(out)]
    assert mod.main(argv) == 0
    assert {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in hashes} == hashes
    assert sorted(p.name for p in out.iterdir()) == [
        "documents.csv", "emails.csv", "human_intervention.csv", "ledger_diff.csv",
        "policy_spec.json", "report.md", "summary.json"]
    emails = (out / "emails.csv").read_text(encoding="utf-8").splitlines()
    assert emails[0].startswith("email_id,cola,direccion,asunto,documentos_cotizacion,clasificacion_propuesta,"
                                "oportunidad_propuesta,nivel_de_confianza,automatizable")
    assert len(emails) == 3
    summary = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    assert summary["inputs_sha256"] == summary["inputs_sha256_after"]
    assert summary["documents_by_confidence"] == {"high": 1, "low": 1}
    # A second run refuses to overwrite the report.
    assert mod.main(argv) == 2
