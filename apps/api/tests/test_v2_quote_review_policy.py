def test_regression_universidad_adventista_conflict_and_revision(world) -> None:
    world.email(1, [world.file("CN1065-a.pdf", _oq("01065-26", "Dra. Ana Prueba – Universidad Adventista de Chile"))],
                thread="ua")
    world.email(2, [world.file("CN01065-b.pdf", _oq("01065-26", "Juan Prueba – Universidad de Valparaiso"))],
                thread="uv")
    world.email(3, [world.file("CN1065A-a.pdf", _oq("01065A-26", "Dra. Ana Prueba – Universidad Adventista de Chile"))],
                thread="ua")
    review, _ = _run(world)
    adventista = next(c.sha256 for c in review.candidates if c.printed_quote_numbers == ("01065-26",)
                      and "Adventista" in c.client_evidence_lines()[0])
    _, run = _run(world, doc_ledger=[_doc_decision(adventista, 1, "01065-26")])
    v = run.documents[adventista]
