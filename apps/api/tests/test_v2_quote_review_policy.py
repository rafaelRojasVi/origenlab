def test_every_rule_names_a_precedent_and_every_reason_names_a_rule() -> None:
    assert [r.id for r in qp.POLICY] == [f"P{n:02d}" for n in range(1, 14)]
    for r in qp.POLICY:
        assert r.title and r.outcome and r.precedent
    reasons = {v for k, v in vars(qp).items() if k.startswith("R_")}
    assert reasons == set(qp.REASON_RULE)
    assert set(qp.REASON_RULE.values()) <= set(qp.RULES)


def test_issuer_is_read_from_the_header_only() -> None:
    assert qp.document_issuer("\n".join(ORIGEN + ["COTIZACIÓN N° 1-26", "At. X"])) == qp.ISSUER_ORIGENLAB
    assert qp.document_issuer("\n".join(LABDELIVERY + ["COTIZACIÓN N° 1-26"])) == qp.ISSUER_LABDELIVERY
    assert qp.document_issuer("\n".join(FOREIGN + ["COTIZACION N°1338/2026"])) == qp.ISSUER_FOREIGN
    # OrigenLab named below the quotation line (a client block, an item) is not the issuer.
    assert qp.document_issuer("\n".join(FOREIGN + ["COTIZACION N°1", "At. OrigenLab"])) == qp.ISSUER_FOREIGN
    assert qp.document_issuer("") == qp.ISSUER_UNKNOWN


def test_quote_numbers_compare_by_serial_letter_and_year() -> None:
    assert qp.same_quote_number("01062-26", "1062-26")
    assert qp.same_quote_number("CN01005", "1005-26")  # a typed CN carries no year
    assert qp.same_quote_number("012092A-26", "12092A-26")
    assert not qp.same_quote_number("012092A-26", "12092-26")
    assert not qp.same_quote_number("011728A-25", "011728A-26")
    assert not qp.same_quote_number(None, "1005-26")


