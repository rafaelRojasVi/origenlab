def test_regression_bioeq_resend_in_the_same_thread_is_one_quotation(world) -> None:
    leaflet = world.file("Leaflet-Ejemplo.PDF", BROCHURE)
    quote = world.file("CN01005-Bioeq SpA.pdf", _oq("1005-26", "Bioeq SpA"))
    world.email(1, [quote, leaflet], thread="bioeq")
    world.email(2, [quote, leaflet], thread="bioeq")
    review, run = _run(world, email_ledger=[
        _email_decision(1, qr.DECISION_CONFIRM, "CN01005", "create_new"),
        _email_decision(2, qr.DECISION_PENDING),
    ])
    (v,) = run.documents.values()
    assert v.automatable and v.canonical_email_id == 1 and v.proposed_quote_number == "1005-26"
    by_id = {e.email_id: e for e in run.emails}
    assert by_id[1].classification == qp.CLS_CUSTOMER_QUOTATION
    assert by_id[2].classification == qp.CLS_DUPLICATE_OCCURRENCE and "P01" in by_id[2].rules
    assert by_id[2].proposed_opportunity.startswith("attach to document")
    # The reconciled email confirmation and both email decisions agree with the policy.
    assert _comparison(run, v.sha256).outcome == qp.AGREE_AUTOMATABLE
    assert _comparison(run, v.sha256).human_source == "email_reconciliation"
    assert _comparison(run, "1").outcome == qp.AGREE_AUTOMATABLE
    assert _comparison(run, "2").outcome == qp.AGREE_AUTOMATABLE


