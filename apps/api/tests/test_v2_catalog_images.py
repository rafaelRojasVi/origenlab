def test_image_path_is_content_addressed_per_product() -> None:
    sha = "a" * 64
    assert image_path(uuid.UUID(PID), sha, "image/jpeg") == f"products/{PID}/{sha}.jpg"
    assert image_path(uuid.UUID(PID), sha, "image/png") == f"products/{PID}/{sha}.png"
    assert image_path(uuid.UUID(PID), sha, "image/webp") == f"products/{PID}/{sha}.webp"
    with pytest.raises(ValueError):
        image_path(uuid.UUID(PID), sha, "image/gif")
    with pytest.raises(ValueError):
        image_path(uuid.UUID(PID), "not-a-hash", "image/png")


