def _repo(dsn: str):
    from origenlab_api.v2.catalog.commands import V2CatalogRepository

    return V2CatalogRepository(psycopg.connect, runtime_dsn(dsn))


def _add(dsn: str, operator: OperatorIdentity, product_id: str, data: bytes, content_type: str = "image/png",
         key: str | None = None, **extra) -> dict:
    from origenlab_api.v2.catalog.routes import AddProductImageFields

    sha = _sha(data)
    body = AddProductImageFields(product_id=product_id, sha256=sha, content_type=content_type,
                                 storage_path=image_path(uuid.UUID(product_id), sha, content_type), **extra)
    return _repo(dsn).execute(command_name="add-product-image", operator=operator,
                              fields=body.model_dump(mode="json"), idempotency_key=key or uuid.uuid4().hex,
                              digest=request_digest("add-product-image", body))


def _update(dsn: str, operator: OperatorIdentity, raw: dict) -> dict:
    from origenlab_api.v2.catalog.routes import UpdateProductImageBody

    body = UpdateProductImageBody(**raw)
    return _repo(dsn).execute(command_name="update-product-image", operator=operator,
                              fields=body.model_dump(mode="json"), idempotency_key=uuid.uuid4().hex,
                              digest=request_digest("update-product-image", body))


def _images(dsn: str, product_id: str) -> list[dict]:
    with psycopg.connect(dsn, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("set role origenlab_owner")
        cur.execute("select * from catalog.product_image where product_id = %s order by sort_order, created_at",
                    (product_id,))
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r, strict=True)) for r in cur.fetchall()]


def _events(dsn: str, product_id: str) -> list[tuple]:
    return _owner(dsn, "select seq, event_type, payload, actor_kind, actor_operator_id::text from crm.domain_event "
                       "where aggregate_kind = 'product' and aggregate_id = %s order by seq", (product_id,))


