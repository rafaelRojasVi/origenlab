def test_check_image_refuses_more_than_eight_mebibytes_as_413() -> None:
    assert MAX_IMAGE_BYTES == 8_388_608
    big = _png() + b"\x00" * (MAX_IMAGE_BYTES - len(_png()) + 1)
    with pytest.raises(ImageRefused) as exc:
        check_image(big, "image/png")
    assert (exc.value.status_code, exc.value.code) == (413, "image_too_large")
    exact = _png() + b"\x00" * (MAX_IMAGE_BYTES - len(_png()))
    assert check_image(exact, "image/png") == "image/png"


