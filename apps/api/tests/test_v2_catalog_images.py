# ──────────────────────────────────────────────────────────── synthetic images ──

def _png(seed: int = 0) -> bytes:
    """A real 1×1 PNG whose single pixel colour is the seed, so seeds give different hashes."""
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    pixel = bytes([0, seed % 256, (seed // 256) % 256, 7])
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(pixel)) + chunk(b"IEND", b""))


def _jpeg(seed: int = 0) -> bytes:
    return b"\xff\xd8\xff\xe0\x00\x10JFIF\x00" + bytes([seed % 256]) * 32 + b"\xff\xd9"


def _webp(seed: int = 0) -> bytes:
    body = b"WEBPVP8L" + struct.pack("<I", 8) + bytes([seed % 256]) * 8
    return b"RIFF" + struct.pack("<I", len(body)) + body


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


