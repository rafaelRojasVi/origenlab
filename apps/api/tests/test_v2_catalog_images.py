def _ungranted_locks(dsn: str) -> int:
    with psycopg.connect(dsn, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("select count(*) from pg_locks where not granted")
        return cur.fetchone()[0]


@needs_db
def test_concurrent_images_on_one_product_take_consecutive_event_positions(disposable_database, db_operator) -> None:
    """Two uploads and an update on one product while a third transaction holds the product: all
    three wait on the product row (the stream owner), then append one after the other."""
    dsn = disposable_database
    pid = _product(dsn)
    image_id = _add(dsn, db_operator, pid, _png(80))["image_id"]
    results: dict[str, object] = {}

    def run(name, fn) -> None:
        try:
            results[name] = fn()
        except Exception as exc:  # noqa: BLE001 - the assertion below names it
            results[name] = exc

    jobs = {
        "a": lambda: _add(dsn, db_operator, pid, _png(81)),
        "b": lambda: _add(dsn, db_operator, pid, _png(82)),
        "u": lambda: _update(dsn, db_operator, {"image_id": image_id, "expected_version": 1, "sort_order": 5}),
    }
    with psycopg.connect(dsn) as holder, holder.cursor() as cur:
        cur.execute("set role origenlab_owner")
        cur.execute("select id from catalog.product where id = %s for update", (pid,))
        threads = [threading.Thread(target=run, args=item) for item in jobs.items()]
        for t in threads:
            t.start()
        deadline = time.monotonic() + 10
        while _ungranted_locks(dsn) < 3 and time.monotonic() < deadline:
            time.sleep(0.05)
        assert _ungranted_locks(dsn) >= 3 and all(t.is_alive() for t in threads)
        holder.commit()
    for t in threads:
        t.join(timeout=30)
    assert all(isinstance(r, dict) and r["ok"] for r in results.values()), results
    events = _events(dsn, pid)
    assert [e[0] for e in events] == [1, 2, 3, 4]
    assert sorted(e[1] for e in events[1:]) == ["product.image_added", "product.image_added", "product.image_updated"]
    assert len(_images(dsn, pid)) == 3


