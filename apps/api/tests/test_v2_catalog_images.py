# ──────────────────────────────────────────────────────── SupabaseStorage over HTTP ──

def _supabase(handler) -> tuple[SupabaseStorage, list[httpx.Request]]:
    seen: list[httpx.Request] = []

    def record(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        return handler(request)

    return SupabaseStorage(BASE, KEY, httpx.Client(transport=httpx.MockTransport(record))), seen


def test_put_if_absent_posts_the_bytes_without_upsert() -> None:
    storage, seen = _supabase(lambda r: httpx.Response(200, json={"Key": "catalog/products/p/a.png"}))
    storage.put_if_absent(f"products/{PID}/{'b' * 64}.png", _png(), "image/png")
    [request] = seen
    assert request.method == "POST"
    assert str(request.url) == f"{BASE}/storage/v1/object/catalog/products/{PID}/{'b' * 64}.png"
    assert request.headers["authorization"] == f"Bearer {KEY}"
    assert request.headers["apikey"] == KEY
    assert request.headers["x-upsert"] == "false"
    assert request.headers["content-type"] == "image/png"
    assert request.content == _png()


