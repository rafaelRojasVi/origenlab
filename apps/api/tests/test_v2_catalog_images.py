class _Lookup(OperatorLookup):
    def __init__(self, operator):
        self._operator = operator

    def by_email(self, email_norm):
        return self._operator


class _FakeRepo:
    """Records each command and what Storage held at that moment."""

    def __init__(self, storage, refusal: CommandRefused | None = None):
        self.calls: list[dict] = []
        self.stored_at_call: list[set] = []
        self._storage = storage
        self._refusal = refusal

    def execute(self, **kwargs):
        self.calls.append(kwargs)
        self.stored_at_call.append(set(getattr(self._storage, "objects", {})))
        if self._refusal is not None:
            raise self._refusal
        return {"ok": True, "replayed": False}


class _FakeReads:
    def __init__(self, images: dict[str, dict]):
        self._images = images

    def image(self, image_id):
        return self._images.get(str(image_id))

    def product_exists(self, product_id):
        return str(product_id) == PID


def _operator(role: str) -> OperatorIdentity:
    return OperatorIdentity(operator_id="00000000-0000-4000-8000-000000000001", email_norm="op@example.test",
                            display_name="Op", role=role, status="active")


def _client(role="sales", *, storage="fake", refusal=None, images=None):
    from origenlab_api.v2.catalog.routes import catalog_command_router, catalog_read_router

    app = FastAPI()
    register_exception_handlers(app)  # the envelope production serves, not FastAPI's default
    app.include_router(catalog_read_router)
    app.include_router(catalog_command_router)
    app.state.catalog_storage = FakeStorage() if storage == "fake" else storage
    app.state.catalog_repository = _FakeRepo(app.state.catalog_storage, refusal)
    app.state.catalog_reads = _FakeReads(images or {})
    app.state.v2_identity = LocalDevIdentity(LOOPBACK, _Lookup(_operator(role)))
    return app, TestClient(app)


def _ikey():
    return {**HEADERS, "Idempotency-Key": uuid.uuid4().hex}


def _upload(client, data: bytes, content_type: str = "image/png", *, headers=None, **form):
    return client.post("/v2/commands/add-product-image", headers=headers or _ikey(),
                       data={"product_id": PID, **form}, files={"file": ("foto.bin", data, content_type)})


def test_upload_stores_the_object_first_then_runs_the_command_over_its_hash() -> None:
    app, client = _client()
    data = _png(1)
    r = _upload(client, data, caption_es="Vista frontal", source="manufacturer_site",
                source_url="https://fabricante.example/sonicador")
    assert r.status_code == 200, r.text
    path = f"products/{PID}/{_sha(data)}.png"
    assert app.state.catalog_storage.objects == {path: (data, "image/png")}
    [call] = app.state.catalog_repository.calls
    assert app.state.catalog_repository.stored_at_call == [{path}]  # Storage before the transaction
    assert call["command_name"] == "add-product-image" and call["operator"].role == "sales"
    assert call["fields"] == {"product_id": PID, "sha256": _sha(data), "content_type": "image/png",
                              "storage_path": path, "caption_es": "Vista frontal", "source": "manufacturer_site",
                              "source_url": "https://fabricante.example/sonicador"}
    json.dumps(call["fields"])
    # The digest covers the hash and the form, never the bytes.
    from origenlab_api.v2.catalog.routes import AddProductImageFields

    assert call["digest"] == request_digest("add-product-image", AddProductImageFields(**call["fields"]))


