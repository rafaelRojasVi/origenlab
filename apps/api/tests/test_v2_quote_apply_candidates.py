def test_a_clean_undecided_quotation_is_a_safe_confirmation(world) -> None:
    world.email(1, [world.file("CN01022-Ana Prueba - Synthon.pdf", _oq("01022-26", "Ana Prueba - Synthon"))])
    review, run = _run(world)
    a = _only(qa.build_apply_candidates(run, review, {}))
    assert (a.separation, a.action, a.ledger_state) == (qa.SEPARATION_SAFE, qa.ACTION_CONFIRM, qa.LEDGER_UNDECIDED)
    assert a.printed_number == "01022-26" and a.number_key == "1022-26" and a.serial == 1022
    assert a.organization == "Synthon" and a.contact == "Ana Prueba"
    assert a.rules == ("P13",) and a.suggestion_reasons == ()
    assert a.safe_fields == ("clasificacion=customer_quotation", "numero=01022-26", "correo_canonico=1")
    # The opportunity and the CRM link are the operator's, even for a safe document.
    assert a.suggestion_fields[0] == "oportunidad=nueva (create_new) propuesta"
    assert "organizacion_crm=Synthon" in a.suggestion_fields
    assert not any(f.startswith("cotizacion=") for f in a.suggestion_fields)
    assert qa.max_printed_serial(review, {a.sha256: qp.ISSUER_ORIGENLAB}) == 1022


