def _states(world, review, doc_ledger: list[dict]):
    path = world.root / "review" / dr.DOCUMENT_LEDGER_FILE
    path.write_text("".join(json.dumps(r) + "\n" for r in doc_ledger), encoding="utf-8")
    return effective_document_states(review, dr.DocumentDecisionLedger(path), {})


def _only(cands: list[qa.ApplyCandidate]) -> qa.ApplyCandidate:
    (a,) = cands
    return a


