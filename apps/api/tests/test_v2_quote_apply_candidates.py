def test_an_owner_confirmation_that_agrees_needs_nothing_applied(world) -> None:
    world.email(1, [world.file("CN01022-Ana Prueba - Synthon.pdf", _oq("01022-26", "Ana Prueba - Synthon"))])
    review, run = _run(world)
    sha = _sha_of(review, "01022-26")
    states = _states(world, review, [_doc_decision(sha, 1, "1022-26")])
    a = _only(qa.build_apply_candidates(run, review, states))
    assert (a.separation, a.action, a.ledger_state) == (
        qa.SEPARATION_SAFE, qa.ACTION_NONE_ALREADY_CONFIRMED, qa.LEDGER_CONFIRMED_AGREES)
    assert a.planned_opportunity_id == "00000000-0000-4000-8000-000000000001"
    assert "el ledger guarda 1022-26; el PDF imprime 01022-26 (mismo número)" in a.notes


def test_an_owner_decision_that_differs_is_never_overridden(world) -> None:
    world.email(1, [world.file("CN01022-Ana Prueba - Synthon.pdf", _oq("01022-26", "Ana Prueba - Synthon"))])
    review, run = _run(world)
    sha = _sha_of(review, "01022-26")
    for row in ([_doc_decision(sha, 1, None, decision=qr.DECISION_REJECT)],
                [_doc_decision(sha, 1, "1023-26")]):
        a = _only(qa.build_apply_candidates(run, review, _states(world, review, row)))
        assert a.ledger_state == qa.LEDGER_DIFFERS
        assert a.suggestion_reasons == (qa.S_LEDGER_DIFFERS,) and a.safe_fields == ()


