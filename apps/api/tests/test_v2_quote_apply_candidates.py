def test_a_serial_at_or_beyond_the_approved_seed_is_only_a_suggestion(world) -> None:
    world.email(1, [world.file("CN01235-Ana Prueba - Nogal.pdf", _oq("01235-26", "Ana Prueba - Nogal"))])
    world.email(2, [world.file("CN01234-Luis Prueba - Arauco.pdf", _oq("01234-26", "Luis Prueba - Arauco"))])
    review, run = _run(world)
    by_number = {a.printed_number: a for a in qa.build_apply_candidates(run, review, {})}
    at_seed, below = by_number["01235-26"], by_number["01234-26"]
    assert at_seed.separation == qa.SEPARATION_SUGGESTION and at_seed.action == qa.ACTION_OPERATOR
    assert at_seed.suggestion_reasons == (qa.S_AT_OR_BEYOND_SEED,)
    assert at_seed.safe_fields == ()
    assert at_seed.suggestion_fields[0] == "cotizacion=customer_quotation 01235-26"
    assert below.separation == qa.SEPARATION_SAFE


