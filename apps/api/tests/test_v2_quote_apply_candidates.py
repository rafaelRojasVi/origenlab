def test_the_policy_is_frozen_at_the_owner_accepted_version() -> None:
    assert qp.policy_fingerprint() == qp.FROZEN_POLICY_SHA256
    assert qp.assert_policy_frozen() == qp.FROZEN_POLICY_SHA256


@pytest.mark.parametrize("field", ["id", "title", "outcome", "precedent"])
def test_changing_any_rule_text_breaks_the_freeze(field: str) -> None:
    changed = list(qp.POLICY)
    changed[2] = dataclasses.replace(changed[2], **{field: getattr(changed[2], field) + "."})
    with pytest.raises(qp.PolicyChanged):
        qp.assert_policy_frozen(changed)
    with pytest.raises(qp.PolicyChanged):
        qp.assert_policy_frozen(qp.POLICY[:-1])


