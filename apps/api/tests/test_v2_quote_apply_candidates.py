def _load_script():
    sys.path.insert(0, str(_SCRIPTS))
    try:
        spec = importlib.util.spec_from_file_location("quote_high_confidence_apply_report", _SCRIPT)
        mod = importlib.util.module_from_spec(spec)
        assert spec.loader is not None
        spec.loader.exec_module(mod)
        return mod
    finally:
        sys.path.remove(str(_SCRIPTS))


def test_the_script_writes_only_its_report_and_leaves_the_ledgers_untouched(world, tmp_path) -> None:
    quote = world.file("CN01005-Bioeq SpA.pdf", _oq("1005-26", "Bioeq SpA"))
    world.email(1, [quote])
    world.email(2, [world.file("CN01236-Ana Prueba - Nogal.pdf", _oq("01236-26", "Ana Prueba - Nogal"))])
    world.email(3, [world.file("CN1051-x.pdf", _oq("01051-26", "hola@ongo.example.cl"))])
    report, _ = world.audit()
    identity = tmp_path / "identity"
    (identity / "texts").mkdir(parents=True)
    (identity / "quote_document_identity.json").write_text(json.dumps(report), encoding="utf-8")
    for d in report["documents"]:
        text = qd.extract_text(world.docs_dir / f"{d['sha256']}.pdf").text
        (identity / "texts" / f"{d['sha256']}.txt").write_text(text, encoding="utf-8")
    ledger = tmp_path / "review" / "decisions.jsonl"
    ledger.parent.mkdir()
    ledger.write_text("", encoding="utf-8")
    doc_ledger = ledger.with_name(dr.DOCUMENT_LEDGER_FILE)
    doc_ledger.write_text(json.dumps(_doc_decision(quote[1], 1, "1005-26")) + "\n", encoding="utf-8")
    hashes = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in (ledger, doc_ledger)}

    mod = _load_script()
    out = tmp_path / "out"
    argv = ["--staging-dir", str(world.staging_dir), "--identity-dir", str(identity), "--ledger", str(ledger),
            "--compare-dryrun", str(tmp_path / "no-dryrun"), "--out", str(out)]
    assert mod.main(argv) == 0
    assert {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in hashes} == hashes
    assert sorted(p.name for p in out.iterdir()) == [
        "high_confidence_apply_candidates.csv", "high_confidence_review.md", "human_review_hold.csv",
        "policy_freeze.json", "summary.json"]
    summary = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    assert summary["applied"] is False
    assert summary["by_action"] == {qa.ACTION_NONE_ALREADY_CONFIRMED: 1, qa.ACTION_OPERATOR: 1}
    assert summary["human_review_hold"] == 1
    freeze = json.loads((out / "policy_freeze.json").read_text(encoding="utf-8"))
    assert freeze["policy_fingerprint_sha256"] == qp.FROZEN_POLICY_SHA256
    assert freeze["inputs_sha256"] == freeze["inputs_sha256_after"]
    md = (out / "high_confidence_review.md").read_text(encoding="utf-8")
    assert "## Confirmación segura (1)" in md and "## Solo sugerencia para el operador (1)" in md
    assert mod.main(argv) == 2  # never overwrites

    # A dry run whose high-confidence set differs stops the report before anything is written.
    dryrun = tmp_path / "dryrun"
    dryrun.mkdir()
    (dryrun / "documents.csv").write_text("sha256,nivel_de_confianza\nabc,alta\n", encoding="utf-8")
    other = tmp_path / "out2"
    assert mod.main([*argv[:-4], "--compare-dryrun", str(dryrun), "--out", str(other)]) == 4
    assert not other.exists()


def _script_inputs(world, tmp_path):
    world.email(1, [world.file("CN01236-Ana Prueba - Nogal.pdf", _oq("01236-26", "Ana Prueba - Nogal"))])
    report, _ = world.audit()
    identity = tmp_path / "identity"
    (identity / "texts").mkdir(parents=True)
    (identity / "quote_document_identity.json").write_text(json.dumps(report), encoding="utf-8")
    for d in report["documents"]:
        text = qd.extract_text(world.docs_dir / f"{d['sha256']}.pdf").text
        (identity / "texts" / f"{d['sha256']}.txt").write_text(text, encoding="utf-8")
    ledger = tmp_path / "review" / "decisions.jsonl"
    ledger.parent.mkdir()
    ledger.write_text("", encoding="utf-8")
    ledger.with_name(dr.DOCUMENT_LEDGER_FILE).write_text("", encoding="utf-8")
    return ["--staging-dir", str(world.staging_dir), "--identity-dir", str(identity), "--ledger", str(ledger),
            "--compare-dryrun", str(tmp_path / "no-dryrun")]


def test_a_proposed_seed_must_clear_every_printed_serial(world, tmp_path) -> None:
    mod = _load_script()
    base = _script_inputs(world, tmp_path)
    audit = tmp_path / "seed-audit"
    audit.mkdir()
    (audit / "resumen.json").write_text(json.dumps({"max_current_series_serial": 1242}), encoding="utf-8")

    # Not above the staged 01236-26, reserved, or not above what the audit found beyond the staging.
    for extra, out in ((["--seed-next-serial", "1236"], "o1"), (["--seed-next-serial", "1500"], "o2"),
                       (["--seed-next-serial", "1242", "--seed-audit", str(audit)], "o3")):
        assert mod.main([*base, *extra, "--out", str(tmp_path / out)]) == 6
        assert not (tmp_path / out).exists()

    out = tmp_path / "ok"
    assert mod.main([*base, "--seed-next-serial", "1243", "--seed-audit", str(audit), "--out", str(out)]) == 0
    summary = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    assert summary["seed"]["next_serial"] == 1243 and summary["seed"]["status"] == "propuesta, sin aprobar"
    assert summary["seed"]["audit_max_current_series"] == 1242
    assert summary["by_separation"] == {qa.SEPARATION_SAFE: 1}  # 01236-26 is below the proposed seed
    freeze = json.loads((out / "policy_freeze.json").read_text(encoding="utf-8"))
    assert (freeze["approved_seed_next_serial"], freeze["seed_next_serial_used"]) == (1235, 1243)
    assert "semilla **1243** (propuesta, sin aprobar)" in (out / "high_confidence_review.md").read_text(encoding="utf-8")


def test_the_approved_seed_is_reported_even_when_stale(world, tmp_path) -> None:
    mod = _load_script()
    out = tmp_path / "out"
    assert mod.main([*_script_inputs(world, tmp_path), "--out", str(out)]) == 0
    summary = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    assert summary["seed"]["status"] == "aprobada" and summary["by_separation"] == {qa.SEPARATION_SUGGESTION: 1}
    md = (out / "high_confidence_review.md").read_text(encoding="utf-8")
    assert "correlativo ≥ 1235, la semilla aprobada" in md and "Semilla de numeración desactualizada" in md
