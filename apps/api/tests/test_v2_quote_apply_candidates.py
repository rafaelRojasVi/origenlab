def test_the_module_opens_no_file_and_imports_no_driver() -> None:
    import ast
    tree = ast.parse(Path(qa.__file__).read_text(encoding="utf-8"))
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    forbidden = ("psycopg", "sqlite3", "sqlalchemy", "googleapiclient", "requests", "httpx", "urllib",
                 "subprocess", "os", "pathlib", "origenlab_api.v2.repository", "origenlab_api.v2.command")
    assert not [m for m in imported if m.startswith(forbidden)], imported
    calls = {getattr(n.func, "attr", getattr(n.func, "id", None)) for n in ast.walk(tree) if isinstance(n, ast.Call)}
    assert not calls & {"open", "write_text", "write_bytes", "unlink", "mkdir"}


