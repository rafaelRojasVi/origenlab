def test_one_email_with_one_quote_document_reconciles(world, tmp_path) -> None:
    quote, brochure = _quote_with_duplicate(world)
    staging, review = _build(world)
    ledger, doc_ledger = _ledgers(tmp_path)

    assert review.quote_document_count(1) == 1  # the brochure is not a quotation
    assert rc.email_confirmation_refusal(review, 1, "CN01005") is None
    entry = rc.record_email_decision(
        staging, ledger, review, 1, decision=qr.DECISION_CONFIRM, operator=OPERATOR,
        opportunity_mode=qr.OPPORTUNITY_CREATE_NEW, quote_number="CN01005",
        quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL,
    )
    (r,) = rc.reconcile_email_confirmations(review, ledger.states())
    assert (r.email_id, r.outcome, r.document_sha256) == (1, rc.RECONCILED, quote)
    assert r.email_decision["decision_id"] == entry["decision_id"]
    assert not doc_ledger.path.exists()  # reconciliation is computed, never written


