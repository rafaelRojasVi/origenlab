def _with_drive_id(world: World, email_id: int, sha: str, drive_id: str) -> None:
    for rec in world.records:
        if rec["payload"]["source_email_id"] == email_id:
            for d in rec["payload"]["documents"]:
                if d["sha256"] == sha:
                    d["drive_file_id"] = drive_id


def test_drive_evidence_matches_by_exact_id_and_local_hash(world) -> None:
    quote, _ = _quote_with_duplicate(world)
    _with_drive_id(world, 1, quote, DRIVE_ID)
    staging, review = _build(world)
    data = next(world.docs_dir.glob(f"{quote}.pdf")).read_bytes()

    meta = {"id": DRIVE_ID, "name": "CN01005-Cliente Ejemplo SpA.pdf", "mimeType": "application/pdf",
            "modifiedTime": "2026-03-18T18:00:00.000Z", "md5Checksum": "not-trusted"}
    good = de.drive_fetch_record(DRIVE_ID, meta, data, fetched_at=FETCHED_AT)
    assert good.sha256 == hashlib.sha256(data).hexdigest() == quote
    # Same name, another id: not the file the manifest names, so attached to nothing.
    lookalike = de.drive_fetch_record("9ZzZzZzZzZzZzZzZzZzZzZ", {**meta, "id": "9ZzZzZzZzZzZzZzZzZzZzZ"},
                                      data, fetched_at=FETCHED_AT)
    idx = de.build_drive_evidence(staging, review, {DRIVE_ID: good, lookalike.drive_file_id: lookalike})
    (ev,) = idx.for_document(quote)
    assert (ev.status, ev.drive_file_id, ev.manifest_occurrences[0][0]) == (de.DRIVE_HASH_MATCH, DRIVE_ID, 1)
    assert (ev.fetch.name, ev.fetch.mime_type, ev.fetch.modified_time) == (
        "CN01005-Cliente Ejemplo SpA.pdf", "application/pdf", "2026-03-18T18:00:00.000Z")
    assert idx.unreferenced_fetches == (lookalike,)

    changed = de.drive_fetch_record(DRIVE_ID, meta, data + b"\n", fetched_at=FETCHED_AT)
    (ev,) = de.build_drive_evidence(staging, review, {DRIVE_ID: changed}).for_document(quote)
    assert ev.status == de.DRIVE_HASH_MISMATCH and quote in ev.reason

    with pytest.raises(qr.StagingInconsistent, match="not the same file"):
        de.drive_fetch_record(DRIVE_ID, {**meta, "id": "1OtherOtherOtherOther"}, data, fetched_at=FETCHED_AT)


def test_drive_evidence_is_read_only(world, tmp_path) -> None:
    quote, _ = _quote_with_duplicate(world)
    _with_drive_id(world, 1, quote, DRIVE_ID)
    staging, review = _build(world)
    fetch_file = tmp_path / "drive" / "drive_fetch.json"
    fetch_file.parent.mkdir()
    data = next(world.docs_dir.glob(f"{quote}.pdf")).read_bytes()
    fetch_file.write_text(json.dumps([de.drive_fetch_record(
        DRIVE_ID, {"id": DRIVE_ID, "name": "x.pdf", "mimeType": "application/pdf", "modifiedTime": "t"},
        data, fetched_at=FETCHED_AT).as_dict()]), encoding="utf-8")
    before = _tree(tmp_path)

    idx = de.build_drive_evidence(staging, review, de.load_drive_fetches(fetch_file))
    assert idx.for_document(quote)[0].status == de.DRIVE_HASH_MATCH
    assert _tree(tmp_path) == before

    # The module has no network client and no write path.
    tree = ast.parse(_DRIVE_MODULE.read_text(encoding="utf-8"))
    imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    imported |= {n.module or "" for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
    assert not [m for m in imported if m.startswith(
        ("googleapiclient", "google", "requests", "httpx", "urllib", "subprocess", "sqlite3", "psycopg"))], imported
    calls = {n.func.attr for n in ast.walk(tree) if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)}
    assert not calls & {"write", "write_text", "write_bytes", "unlink", "rename", "replace", "mkdir"}
    opens = [n for n in ast.walk(tree) if isinstance(n, ast.Call) and getattr(n.func, "attr", None) == "open"]
    assert opens and all(not n.args and all(k.arg == "encoding" for k in n.keywords) for n in opens)  # read mode only
    # The reconciliation module never appends to a ledger itself.
    recon = ast.parse(_RECONCILE_MODULE.read_text(encoding="utf-8"))
    ledger_writes = [n for n in ast.walk(recon) if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
                     and n.func.attr == "append" and "ledger" in ast.unparse(n.func.value)]
    assert ledger_writes == []


