def _build(world: World) -> tuple[qr.Staging, dr.DocumentReview]:
    report, _ = world.audit()
    staging = qr.load_staging(world.staging_dir)
    return staging, dr.build_document_review(staging, report)


def _ledgers(tmp_path: Path) -> tuple[qr.DecisionLedger, dr.DocumentDecisionLedger]:
    ledger = qr.DecisionLedger(tmp_path / "review" / "decisions.jsonl")
    return ledger, dr.DocumentDecisionLedger(ledger.path.with_name(dr.DOCUMENT_LEDGER_FILE))


def _historical_email_confirm(staging, ledger, email_id, number, **kw) -> dict:
    """An email-level confirmation recorded before this policy existed (as 706492 was)."""
    kw.setdefault("opportunity_mode", qr.OPPORTUNITY_CREATE_NEW)
    entry = qr.build_decision(
        staging.item(email_id), decision=qr.DECISION_CONFIRM, operator=OPERATOR,
        quote_number=number, quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL, **kw,
    )
    ledger.append(entry)
    return entry


def _bytes(*paths: Path) -> dict[str, bytes | None]:
    return {str(p): (p.read_bytes() if p.exists() else None) for p in paths}


def _tree(root: Path) -> dict[str, bytes]:
    return {str(p): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


