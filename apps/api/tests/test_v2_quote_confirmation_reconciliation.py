def _quote_with_duplicate(world: World) -> tuple[str, str]:
    """The 706492/706499 shape: one quotation plus a brochure, resent in the same thread."""
    quote = world.file("CN01005-Cliente Ejemplo SpA.pdf", _quote("1005-26", "Cliente Ejemplo SpA"))
    brochure = world.file("Leaflet-Ejemplo.PDF", BROCHURE)
    world.email(1, [quote, brochure], thread="t-quote")
    world.email(2, [quote, brochure], thread="t-quote")
    return quote[1], brochure[1]


def _two_quote_email(world: World) -> tuple[str, str]:
    a = world.file("Cotización 1007- Ana Prueba - Eurofarma.pdf", _quote("1007-26", "Ana Prueba - Eurofarma"))
    b = world.file("CN1010-Ana Prueba - Eurofarma.pdf", _quote("1010-26", "Ana Prueba - Eurofarma"))
    world.email(1, [a, world.file("Leaflet-Ejemplo.PDF", BROCHURE), b])
