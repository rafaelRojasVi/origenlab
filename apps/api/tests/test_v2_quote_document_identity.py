def test_bioeq_vs_instafarm_is_different_explicit_client_even_with_a_shared_brochure(world) -> None:
    brochure = world.file("Leaflet-Ejemplo.PDF", BROCHURE)
    world.email(1, [world.file("CN01005-Bioeq SpA.pdf", _quote("1005-26", "Bioeq SpA")), brochure])
    world.email(2, [world.file("Cotización 1006- Ana Prueba - InstaFarm.pdf",
                               _quote("1006-26", "Ana Prueba - InstaFarm")), brochure], proposed=[])
    report, c = world.audit(ocr=_no_ocr)

    rel = _rel(c, 1, 2)
    assert rel["classification"] == qd.DIFFERENT_EXPLICIT_CLIENT
    # The only link is the brochure's bytes, and it is named as such — not as a client link.
    assert rel["links"] == ["shared_generic_document"]
    evidence = [x for p in rel["document_pairs"] for x in p["evidence"]]
    assert "At. Bioeq SpA" in evidence and "At. Ana Prueba - InstaFarm" in evidence
    docs = {d["sha256"]: d for d in report["documents"]}
    assert docs[brochure[1]]["document_class"] == qd.BROCHURE_OR_GENERIC
    insta = next(d for d in report["documents"] if "InstaFarm" in d["filenames"][0])
    assert insta["clients"][0]["contact"] == "Ana Prueba"
    assert insta["clients"][0]["organization"] == "InstaFarm"
    assert c[2]["document_quote_numbers"] == ["1006-26"]
    # The filename proposed nothing; the document prints 1006-26 — shown for review.
    assert qd.REVIEW_PROPOSAL_DISAGREES in c[2]["review_reasons"]


def test_eurofarma_document_printing_two_numbers_stays_with_a_human(world) -> None:
    two = _quote("1007-26", "Ana Prueba - Eurofarma")
    two.insert(6, "COTIZACIÓN N° 1010-26")
    world.email(1, [world.file("CN1010-Ana Prueba - Eurofarma.pdf", two)])
    world.email(2, [world.file("CN1010-Ana Prueba - Eurofarma v2.pdf", _quote("1010-26", "Ana Prueba - Eurofarma"))])
    report, c = world.audit(ocr=_no_ocr)

    doc = next(d for d in report["documents"] if d["email_ids"] == [1])
    assert doc["quote_number"] is None
    assert [q["raw"] for q in doc["quote_numbers_found"]] == ["1007-26", "1010-26"]
    assert qd.REVIEW_QUOTE_NUMBER_CONFLICT in doc["review_reasons"]
    assert c[1]["needs_human_review"]
    # Same explicit client, but the numbers cannot be compared: never "same quote".
    rel = _rel(c, 1, 2)
    assert rel["classification"] == qd.INSUFFICIENT_EVIDENCE
    assert rel["needs_human_review"] is True


