def test_module_imports_no_database_driver_or_network_client() -> None:
    tree = ast.parse(_MODULE.read_text(encoding="utf-8"))
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported |= {a.name for a in node.names}
        elif isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
    forbidden = ("psycopg", "sqlite3", "sqlalchemy", "origenlab_api.v2.repository",
                 "origenlab_api.v2.command", "origenlab_api.v2.case_command", "googleapiclient",
                 "requests", "httpx", "urllib")
    assert not [m for m in imported if m.startswith(forbidden)], imported


def _load_script(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _tree(root: Path) -> dict[str, str]:
    return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file()}


def test_cli_writes_csv_json_and_texts_and_touches_nothing_else(world, tmp_path: Path) -> None:
    brochure = world.file("Leaflet-Ejemplo.PDF", BROCHURE)
    world.email(1, [world.file("CN01005-Bioeq SpA.pdf", _quote("1005-26", "Bioeq SpA")), brochure])
    world.email(2, [world.file("CN01006-x.pdf", _quote("1006-26", "Ana Prueba - InstaFarm")), brochure])
    world.write()
    ledger = world.docs_root / "review" / "decisions.jsonl"
    ledger.parent.mkdir()
    ledger.write_text('{"email_id": 1, "decision": "leave_pending"}\n', encoding="utf-8")
    before = _tree(world.docs_root)

    cli = _load_script(_CLI, "quote_document_identity_cli")
    out = tmp_path / "identity"
    report = cli.run(world.staging_dir, world.docs_root, out, [1, 2, 999], ocr=False)

    assert _tree(world.docs_root) == before  # staging, documents and ledger untouched
    assert sorted(p.name for p in out.iterdir()) == [cli.REPORT_CSV, cli.REPORT_JSON, cli.TEXTS_DIR]
    assert len(list((out / cli.TEXTS_DIR).iterdir())) == 3
    assert json.loads((out / cli.REPORT_JSON).read_text(encoding="utf-8"))["summary"] == report["summary"]
    rows = list(csv.DictReader((out / cli.REPORT_CSV).open(encoding="utf-8")))
    assert {r["email_id"] for r in rows} == {"1", "2"}
