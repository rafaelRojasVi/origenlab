def _quote(number: str, addressee: str, *, date: str = "Valdivia, 18 de marzo del 2026",
           rut: str | None = None, address: str | None = None, model: str = "Osmometro modelo X-100") -> list[str]:
    lines = [*HEADER, date, f"COTIZACIÓN N° {number}", f"At. {addressee}"]
    if rut:
        lines.append(f"RUT: {rut}")
    if address:
        lines.append(f"Dirección: {address}")
    return lines + ["", "Item    Ref.    Detalle    Valor unitario    Total",
                    f"1    X100    {model}, fabricante de ejemplo    $ 1.000    $ 1.000",
                    "Condiciones comerciales", "Plazo de entrega 2 semanas"]


