def _get(port: int, path: str) -> tuple[int, bytes, dict]:
    conn = http.client.HTTPConnection("127.0.0.1", port)
    conn.request("GET", path, headers={"Host": f"127.0.0.1:{port}"})
    resp = conn.getresponse()
    return resp.status, resp.read(), dict(resp.getheaders())


def test_review_page_shows_the_summary_and_links_to_document_evidence(page_server) -> None:
    port, quote, ledger = page_server
    status, body, _ = _get(port, "/")
    html = body.decode()
    assert status == 200 and "Identidad de documentos" in html
    assert "different_explicit_client" in html

    status, body, _ = _get(port, "/item/1")
    html = body.decode()
    assert status == 200
    assert "At. Bioeq SpA" in html
    assert f"/doc/{quote[1]}" in html and f"/doc/{quote[1]}/texto" in html
    assert "shared_generic_document" in html

    status, body, headers = _get(port, f"/doc/{quote[1]}")
    assert status == 200 and headers["Content-Type"] == "application/pdf"
    assert hashlib.sha256(body).hexdigest() == quote[1]
    status, body, _ = _get(port, f"/doc/{quote[1]}/texto")
    assert status == 200 and "COTIZACIÓN N° 1005-26" in body.decode()
    assert not ledger.path.exists()


