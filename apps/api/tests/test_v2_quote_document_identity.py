def test_rut_decides_when_both_documents_print_one() -> None:
    def doc(addressee: str, rut: str) -> qd.ClientAnchor:
        return qd.extract_fields("\n".join(_quote("1-26", addressee, rut=rut))).clients[0]

    assert qd.compare_clients(doc("Empresa Uno SpA", "76.000.001-1"), doc("EMPRESA UNO", "76000001-1"))[0] == qd.SAME
    assert qd.compare_clients(doc("Empresa Uno SpA", "76.000.001-1"), doc("Empresa Uno SpA", "76.000.002-2"))[0] == \
        qd.CONFLICT
    # A person-only anchor cannot be compared with an organization.
    person = qd.extract_fields("At. Ana Prueba").clients[0]
    assert person.organization is None
    assert qd.compare_clients(person, doc("Empresa Uno SpA", "76.000.001-1"))[0] == qd.INCOMPARABLE


