def test_document_page_shows_its_evidence_and_records_its_own_decision(doc_server) -> None:
    port, a, b, ledger, doc_ledger = doc_server
    status, html, _ = _req(port, "GET", f"/documento/{a}", origin=None)
    assert status == 200
    for needle in (a, "Cotización 1007- Ana Prueba - Eurofarma.pdf", "At. Ana Prueba - Eurofarma",
                   "COTIZACIÓN N° 1007-26", "Propuesta", f"/documento/{a}/decide"):
        assert needle in html, needle

    status, _, headers = _req(port, "POST", f"/documento/{a}/decide", {
        "decision": qr.DECISION_CONFIRM, "opportunity_mode": qr.OPPORTUNITY_CREATE_NEW,
        "quote_number": "1007-26", "quote_number_basis": qr.BASIS_CONFIRMED_PROPOSAL,
    })
    assert status == 303 and headers["Location"] == f"/documento/{a}"
    (entry,) = doc_ledger.entries()
    assert (entry["document_sha256"], entry["quote_number"], entry["applied"]) == (a, "1007-26", False)
    assert not ledger.path.exists()  # the email ledger is untouched

    status, html, _ = _req(port, "GET", "/documentos", origin=None)
    assert status == 200 and entry["opportunity"]["planned_opportunity_id"] in html

    # A foreign origin writes nothing; an unknown document is not found.
    status, _, _ = _req(port, "POST", f"/documento/{b}/decide",
                        {"decision": qr.DECISION_PENDING}, origin="http://evil.example")
    assert status == 403
    assert _req(port, "POST", "/documento/" + "0" * 64 + "/decide", {"decision": qr.DECISION_PENDING})[0] == 422
    assert _req(port, "GET", "/documento/" + "0" * 64, origin=None)[0] == 404
    assert len(doc_ledger.entries()) == 1
