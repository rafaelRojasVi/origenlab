def test_conflicting_client_names_in_one_email_require_review(world, tmp_path) -> None:
    a = world.file("CN01020-a.pdf", _quote("1020-26", "Ana Prueba - Eurofarma"))
    b = world.file("CN01021-b.pdf", _quote("1021-26", "Luis Ejemplo - Universidad Inventada"))
    world.email(1, [a, b])
    _, review, _ = _review(world)
    for sha in (a[1], b[1]):
        c = review.candidate(sha)
        assert c.proposed_status == dr.NEEDS_REVIEW
        assert c.proposed_quote_number is None
        assert dr.REVIEW_OTHER_CLIENT_SAME_EMAIL in c.review_reasons

    ledger = _ledger(tmp_path)
    with pytest.raises(qr.ReviewRefused, match="no proposed number"):
        _confirm(review, ledger, a[1], opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                 quote_number="1020-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    with pytest.raises(qr.ReviewRefused, match="needs review"):
        _confirm(review, ledger, a[1], opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                 quote_number="1020-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED)
    assert ledger.entries() == []
    entry = _confirm(review, ledger, a[1], opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                     quote_number="1020-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED,
                     reason="dos clientes distintos en un correo; este PDF es de Eurofarma")
    assert entry["review_reasons_at_decision"] == [dr.REVIEW_OTHER_CLIENT_SAME_EMAIL]


def test_one_printed_number_for_two_clients_requires_review(world) -> None:
    world.email(1, [world.file("CN01046-a.pdf", _quote("01046-26", "Ana Prueba - Eurofarma"))])
    world.email(2, [world.file("CN01046-b.pdf", _quote("01046-26", "Luis Ejemplo - Universidad Inventada"))])
    _, review, _ = _review(world)
    assert len(review.candidates) == 2
    for c in review.candidates:
        assert c.needs_review and c.proposed_quote_number is None
        assert dr.REVIEW_NUMBER_ON_OTHER_CLIENT in c.review_reasons
        (rel,) = c.related
        assert rel.via == (dr.VIA_PRINTED_NUMBER,)
        assert rel.classification == qd.CONFLICTING_CLIENT_EVIDENCE


def test_conflicting_quote_numbers_require_review(world) -> None:
    two = _quote("1007-26", "Ana Prueba - Eurofarma")
    two.insert(6, "COTIZACIÓN N° 1010-26")
    both = world.file("CN1010-Ana Prueba - Eurofarma.pdf", two)
    mismatch = world.file("CN1012-Ana Prueba - Eurofarma.pdf", _quote("1013-26", "Ana Prueba - Eurofarma"))
    world.email(1, [both])
    world.email(2, [mismatch])
    _, review, _ = _review(world)

    c = review.candidate(both[1])
    assert c.printed_quote_numbers == ("1007-26", "1010-26")
    assert c.proposed_quote_number is None and c.needs_review
    assert qd.REVIEW_QUOTE_NUMBER_CONFLICT in c.review_reasons
    m = review.candidate(mismatch[1])
    assert m.printed_quote_numbers == ("1013-26",)
    assert m.proposed_quote_number is None
    assert qd.REVIEW_FILENAME_NUMBER_MISMATCH in m.review_reasons


def test_same_number_on_two_documents_is_a_resend_only_on_one_opportunity(world, tmp_path) -> None:
    v1 = world.file("CN1010-Ana Prueba - Eurofarma.pdf", _quote("1010-26", "Ana Prueba - Eurofarma"))
    v2 = world.file("CN1010-Ana Prueba - Eurofarma v2.pdf",
                    _quote("1010-26", "Ana Prueba - Eurofarma", model="Osmometro modelo X-200"))
    world.email(1, [v1])
    world.email(2, [v2])
    _, review, _ = _review(world)
    for sha in (v1[1], v2[1]):
        c = review.candidate(sha)
        assert dr.REVIEW_NUMBER_ON_OTHER_DOCUMENT in c.review_reasons
        assert c.related[0].classification == qd.SAME_CLIENT_SAME_QUOTE

    ledger = _ledger(tmp_path)
    opp = str(uuid.uuid4())
    _confirm(review, ledger, v1[1], opportunity_mode=qr.OPPORTUNITY_EXISTING, opportunity_id=opp,
             quote_number="1010-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED, reason="primer envío")
    with pytest.raises(qr.ReviewRefused, match="cannot belong to two opportunities"):
        _confirm(review, ledger, v2[1], opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                 quote_number="1010-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED, reason="x")
    with pytest.raises(qr.ReviewRefused, match="needs review"):
        _confirm(review, ledger, v2[1], opportunity_mode=qr.OPPORTUNITY_EXISTING, opportunity_id=opp,
                 quote_number="1010-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED)
    entry = _confirm(review, ledger, v2[1], opportunity_mode=qr.OPPORTUNITY_EXISTING, opportunity_id=opp,
                     quote_number="1010-26", quote_number_basis=qr.BASIS_OPERATOR_ENTERED,
                     reason="revisión del mismo presupuesto, cambia el modelo")
    assert entry["same_quote_number_as"] == [v1[1]]


