@pytest.fixture
def world(tmp_path: Path) -> World:
    return World(tmp_path)


def _review(world: World) -> tuple[qr.Staging, dr.DocumentReview, dict]:
    report, _ = world.audit()
    staging = qr.load_staging(world.staging_dir)
    return staging, dr.build_document_review(staging, report), report


def _two_quote_email(world: World, email_id: int = 1) -> tuple[str, str]:
    """One email, two quotations for the same client, plus a brochure — the 706528 shape."""
    a = world.file("Cotización 1007- Ana Prueba - Eurofarma.pdf", _quote("1007-26", "Ana Prueba - Eurofarma"))
    b = world.file("CN1010-Ana Prueba - Eurofarma.pdf", _quote("1010-26", "Ana Prueba - Eurofarma"))
    world.email(email_id, [a, world.file("Leaflet-Ejemplo.PDF", BROCHURE), b])
    return a[1], b[1]


def _ledger(tmp_path: Path) -> dr.DocumentDecisionLedger:
    return dr.DocumentDecisionLedger(tmp_path / "review" / dr.DOCUMENT_LEDGER_FILE)


def _confirm(review, ledger, sha, **kw):
    kw.setdefault("decision", qr.DECISION_CONFIRM)
    kw.setdefault("operator", OPERATOR)
    return dr.record_document_decision(review, ledger, sha, **kw)


# --- one email, several quotations ------------------------------------------------------


def test_one_email_with_two_quotes_is_two_document_candidates(world) -> None:
    a, b = _two_quote_email(world)
    staging, review, _ = _review(world)

    cands = review.for_email(1)
    assert {c.sha256 for c in cands} == {a, b}  # the brochure is not a candidate
    by_sha = {c.sha256: c for c in cands}
    for sha, number, name in ((a, "1007-26", "Cotización 1007- Ana Prueba - Eurofarma.pdf"),
                              (b, "1010-26", "CN1010-Ana Prueba - Eurofarma.pdf")):
        c = by_sha[sha]
        assert c.filenames == (name,)
        assert c.printed_quote_numbers == (number,)
        assert c.proposed_quote_number == number
        assert c.proposed_status == dr.PROPOSED_QUOTATION
        assert c.client_evidence_lines() == ["At. Ana Prueba - Eurofarma"]
    assert review.quote_document_count(1) == 2

    # One email-level decision cannot pick one of the two quotations.
    email_ledger = qr.DecisionLedger(world.root / "review" / "decisions.jsonl")
    with pytest.raises(qr.ReviewRefused, match="2 quotation documents"):
        qr.record_decision(
            staging, email_ledger, 1, decision=qr.DECISION_CONFIRM, operator=OPERATOR,
            opportunity_mode=qr.OPPORTUNITY_CREATE_NEW, quote_number="CN01010",
            quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL, quote_document_count=2,
        )
    assert email_ledger.entries() == []
    # Saying the message is not a quotation, or leaving it pending, is still an email act.
    qr.record_decision(staging, email_ledger, 1, decision=qr.DECISION_PENDING, operator=OPERATOR,
                       quote_document_count=2)
    assert len(email_ledger.entries()) == 1


def test_same_client_different_numbers_are_decided_separately(world, tmp_path) -> None:
    a, b = _two_quote_email(world)
    _, review, _ = _review(world)
    ca, cb = review.candidate(a), review.candidate(b)
    assert [(r.other_sha256, r.via, r.classification) for r in ca.related] == [
        (b, (dr.VIA_SAME_EMAIL,), qd.SAME_CLIENT_DIFFERENT_QUOTE)
    ]
    assert not ca.review_reasons and not cb.review_reasons

    ledger = _ledger(tmp_path)
    _confirm(review, ledger, a, opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
             quote_number="1007-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    states = ledger.states()
    assert states[a].status == qr.STATUS_CONFIRMED
    assert b not in states  # confirming one quotation says nothing about the other
    dr.record_document_decision(review, ledger, b, decision=qr.DECISION_REJECT, operator=OPERATOR,
                                reason="borrador enviado por error")
    states = ledger.states()
    assert (states[a].status, states[b].status) == (qr.STATUS_CONFIRMED, qr.STATUS_REJECTED)
    # A proposal is the number the document prints — not the other document's.
    with pytest.raises(qr.ReviewRefused, match="not the printed proposal"):
        dr.build_document_decision(cb, decision=qr.DECISION_CONFIRM, operator=OPERATOR,
                                   opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                                   quote_number="1007-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)


def test_exact_duplicate_file_across_emails_is_one_canonical_candidate(world, tmp_path) -> None:
    quote = world.file("CN01005-Bioeq SpA.pdf", _quote("1005-26", "Bioeq SpA"))
    renamed = ("reenvío cotización.pdf", quote[1], quote[2])  # same bytes, another name
    # Inserted later-first: the canonical occurrence is chosen by time, not by file order.
    world.email(3, [renamed], thread="t-b", proposed=["CN01005"])
    world.email(1, [quote], thread="t-a")
    world.email(2, [quote], thread="t-a")
    staging, review, _ = _review(world)

    assert len(review.candidates) == 1
    c = review.candidates[0]
    assert c.sha256 == quote[1]
    assert c.canonical.email_id == 1
    assert [o.email_id for o in c.duplicate_occurrences] == [2, 3]
    assert c.filenames == ("CN01005-Bioeq SpA.pdf", "reenvío cotización.pdf")
    # Every occurrence keeps its own exact identifiers.
    for o in c.occurrences:
        item = staging.item(o.email_id)
        assert (o.gmail_message_id, o.rfc822_message_id, o.gmail_thread_id, o.source_record_sha256) == (
            item.gmail_message_id, item.rfc822_message_id, item.gmail_thread_id, item.source_record_sha256)
    assert [review.quote_document_count(e) for e in (1, 2, 3)] == [1, 1, 1]
    assert c.proposed_status == dr.PROPOSED_QUOTATION

    ledger = _ledger(tmp_path)
    entry = _confirm(review, ledger, quote[1], opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                     quote_number="1005-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    assert entry["canonical_email_id"] == 1
    assert [o["email_id"] for o in entry["occurrences"]] == [1, 2, 3]
    assert len(ledger.states()) == 1  # one document, one status


def test_one_opportunity_with_multiple_quotes(world, tmp_path) -> None:
    a, b = _two_quote_email(world)
    _, review, _ = _review(world)
    ledger = _ledger(tmp_path)

    first = _confirm(review, ledger, a, opportunity_mode=qr.OPPORTUNITY_CREATE_NEW,
                     quote_number="1007-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    planned = first["opportunity"]["planned_opportunity_id"]
    assert first["opportunity"] == {"mode": qr.OPPORTUNITY_CREATE_NEW, "opportunity_id": None,
                                    "planned_opportunity_id": planned}
    # A planned id is joined only when typed, and only if a confirmed document holds it.
    with pytest.raises(qr.ReviewRefused, match="no other confirmed document plans"):
        _confirm(review, ledger, b, opportunity_mode=dr.OPPORTUNITY_PLANNED, opportunity_id=str(uuid.uuid4()),
                 quote_number="1010-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    second = _confirm(review, ledger, b, opportunity_mode=dr.OPPORTUNITY_PLANNED, opportunity_id=planned,
                      quote_number="1010-26", quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    assert second["opportunity"]["planned_opportunity_id"] == planned

    plans = dr.opportunity_plans(review, ledger)
    assert len(plans) == 1
    assert plans[0].opportunity_key == planned and plans[0].mode == dr.OPPORTUNITY_PLANNED
    # One opportunity, two separate quotations.
    assert plans[0].quote_numbers == ("1007-26", "1010-26")
    assert {q.document_sha256 for q in plans[0].quotes} == {a, b}
    assert all(e["applied"] is False for e in ledger.entries())


def test_an_existing_opportunity_can_hold_several_quotes(world, tmp_path) -> None:
    a, b = _two_quote_email(world)
    _, review, _ = _review(world)
    ledger = _ledger(tmp_path)
    opp = str(uuid.uuid4())
    for sha, number in ((a, "1007-26"), (b, "1010-26")):
        _confirm(review, ledger, sha, opportunity_mode=qr.OPPORTUNITY_EXISTING, opportunity_id=opp,
                 quote_number=number, quote_number_basis=qr.BASIS_CONFIRMED_PROPOSAL)
    (plan,) = dr.opportunity_plans(review, ledger)
    assert (plan.opportunity_key, plan.mode, plan.quote_numbers) == (opp, qr.OPPORTUNITY_EXISTING,
                                                                     ("1007-26", "1010-26"))


